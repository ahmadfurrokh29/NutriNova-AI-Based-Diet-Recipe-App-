// lib/main.dart

import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter_dotenv/flutter_dotenv.dart';
import 'package:provider/provider.dart'; // <-- Add this for ChangeNotifierProvider
import 'screens/splash_screen.dart';
import 'screens/auth/signup_screen.dart';
import 'screens/auth/login_screen.dart';
import 'screens/onboarding/profile_setup_screen.dart';
import 'screens/home_screen.dart';
import 'firebase_options.dart'; // generated by Firebase CLI
import 'providers/theme_providers.dart'; // <-- Your ThemeProvider file

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await dotenv.load(fileName: '.env');
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(
    ChangeNotifierProvider(
      create: (_) => ThemeProvider(),
      child: const MyApp(),
    ),
  );
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return Consumer<ThemeProvider>(
      builder: (context, themeProvider, child) {
        return MaterialApp(
          debugShowCheckedModeBanner: false,
          title: 'NutriNova',
          themeMode: themeProvider.mode, // Light or Dark mode
          theme: ThemeData(
            primarySwatch: Colors.green,
            scaffoldBackgroundColor: const Color(0xFFDBD7CF),
            brightness: Brightness.light,
          ),
          darkTheme: ThemeData(
            primarySwatch: Colors.green,
            scaffoldBackgroundColor: Colors.black,
            brightness: Brightness.dark,
          ),
          initialRoute: '/',
          routes: {
            '/': (_) => SplashScreen(),
            '/signup': (_) => const SaladSignupScreen(),
            '/login': (_) => const SaladLoginScreen(),
            '/profile_setup': (_) => ProfileSetupScreen(),
            '/home': (_) => const HomeScreen(),
          },
        );
      },
    );
  }
}
